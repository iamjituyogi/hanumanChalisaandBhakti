/** Chaupai only (the 40 verses), used for the daily verse. */
export const CHAUPAIS = CHALISA.filter(v => /^\d+$/.test(v.id));

/** The same verse for everyone on a given calendar day. */
export function verseOfTheDay(date: Date = new Date()): Verse {
  const dayNumber = Math.floor(
    Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86_400_000,
  );
  return CHAUPAIS[dayNumber % CHAUPAIS.length];
}
